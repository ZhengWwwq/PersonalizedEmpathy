from api_call import api_call
from utils import load_json, save_json, preprocess_data, extract_boxed_score
import numpy as np
import os


base_prompt_response = r'''
You are an expert Psychologist and Empathy Evaluator. Your task is to judge the Assistant Response for the **{dimension}** dimension using the provided Fixed Criteria.

The Fixed Criteria were prepared in advance for this exact user, scenario, query, and dimension. Do not generate new criteria, revise the criteria, or reward anything merely because it seems generally good. Use the task context only to understand and apply the Fixed Criteria accurately.

Score strictly on a 1-5 scale:
- 1 means the response fails the Fixed Criteria or has serious emotional-intelligence problems.
- 3 means the response partially satisfies the Fixed Criteria but misses important requirements.
- 5 means the response perfectly satisfies the Fixed Criteria, including the high-weight and persona-informed requirements.

---

### 1. Fixed Evaluation Criteria
**Dimension:** {dimension}
{criteria}

---

### 2. Task Context
**Memories extracted from previous dialogue:**
{memory}

**Scenario:**
{scenario}

**User Persona:**
{persona}

**User Query:**
{query}

**Assistant Response:**
{response}

---

### 3. Output Requirement
Output exactly two lines:
Analysis: <Briefly analyze how well the response satisfies the Fixed Criteria, especially high-weight criteria and any major misses.>
Scores: <the overall comprehensive score of the response, e.g., \boxed{{x}}>.
'''

def parse_args():
    import argparse
    parser = argparse.ArgumentParser(description="Evaluate Empathy Responses")

    # Mode
    parser.add_argument("--mode", type=str, default="amem", help="Evaluation mode: amem, memoryos, or evermemos")

    # Data path
    parser.add_argument("--dataset_path", type=str, required=True, help="Path to the dataset JSON file")
    parser.add_argument("--predict_path", type=str, required=True, help="Path to the predictions JSON file")
    parser.add_argument("--criteria_path", type=str, default=os.getenv("EVAL_CRITERIA_PATH", ""), help="Optional sidecar criteria JSON generated by prepare_criteria.py")

    # Evaluation settings
    parser.add_argument("--eval_model", type=str, default=os.getenv("EVAL_MODEL", "gpt-4o-mini"), help="OpenAI-compatible model to use for evaluation")
    parser.add_argument("--eval_temperature", type=float, default=0.3, help="Temperature for evaluation model")
    parser.add_argument("--eval_batch_size", type=int, default=128, help="Batch size for evaluation model")
    parser.add_argument("--eval_api_key", type=str, default=os.getenv("EVAL_API_KEY", ""), help="OpenAI-compatible API key")
    parser.add_argument("--eval_base_url", type=str, default=os.getenv("EVAL_BASE_URL", None), help="OpenAI-compatible base URL")
    parser.add_argument("--eval_num", type=int, default=0)

    return parser.parse_args()


def prepare_prompt(dimension: str, memory: str, query: str, response: str, persona: str, scenario: str, criteria: str):
    """Build one fixed-criteria judge prompt for a response and dimension."""
    if "<think>" in response:
        response = response.split("</think>")[-1]
    prompt = base_prompt_response.format(
        dimension=dimension,
        criteria=criteria or "No fixed criteria provided.",
        memory=memory,
        query=query,
        response=response, 
        persona=persona, 
        scenario=scenario
    )
    return [{"role": "user", "content": prompt}]

def attach_criteria_to_processed_data(processed_data, dataset, criteria_data=None):
    """Attach fixed criteria to flattened examples.

    Criteria can either be pre-merged into each dataset query under
    query["criteria"], or stored in the sidecar format produced by
    prepare_criteria.py.
    """
    flat_criteria = []
    if criteria_data:
        for session in criteria_data:
            flat_criteria.extend(session.get("criterias", []))
    else:
        for session in dataset:
            for query_item in session.get("queries", []):
                flat_criteria.append(query_item.get("criteria", {}))

    assert len(processed_data) == len(flat_criteria), (
        f"processed items={len(processed_data)} criteria items={len(flat_criteria)}"
    )

    for item, criteria in zip(processed_data, flat_criteria):
        item["criteria"] = criteria or {}

    return processed_data

def update_score(predicts, scores, dimension):
    """Write dimension scores back into the nested prediction structure."""
    i = 0
    updated_predicts = []
    for response in predicts:
        for r_item in response['responses']:
            r_item[dimension] = scores[i]
            i += 1
        updated_predicts.append(response)
    return updated_predicts

def eval(args):
    """Run PERM fixed-criteria evaluation for resonation, expression, and reception."""
    if not args.eval_api_key:
        raise ValueError("Set EVAL_API_KEY or pass --eval_api_key.")

    dataset = load_json(args.dataset_path)
    predict = load_json(args.predict_path)
    criteria_data = load_json(args.criteria_path) if args.criteria_path else None

    processed_data = preprocess_data(dataset, predict)
    processed_data = attach_criteria_to_processed_data(processed_data, dataset, criteria_data)

    if args.eval_num:
        processed_data = processed_data[:args.eval_num]

    total_results = [{"session_id": item['session_id'], "query_id": item['query_id'], "resonation": {}, "expression": {}, "reception": {}} for item in processed_data]

    total_score = 0.

    final_scores = {}

    for dimension in ['resonation', 'expression', 'reception']:
        print("*" * 10 + f" Evaluating {dimension} " + "*" * 10)

        all_prompts = []
        for item in processed_data:

            memory = item['memory']
            query = item['query']
            response = item['response']
            scenario = item['scenario']
            persona = item['persona']
            criteria = item.get("criteria", {}).get(dimension)

            if response:
                prompt = prepare_prompt(dimension, memory, query, response, persona, scenario, criteria)
                all_prompts.append(prompt)
        # print(all_prompts[0][-1]['content'])
        # input("stop")
        
        all_results = api_call(
            model_name=args.eval_model, 
            user_prompt_list=all_prompts, 
            api_list=[args.eval_api_key], 
            base_url_list=[args.eval_base_url], 
            api_call_limit=args.eval_batch_size, 
            temperature=args.eval_temperature,
            max_completion_tokens=2048,
        )

        eval_scores = [extract_boxed_score(output) for output in all_results]
        for res, score, item in zip(all_results, eval_scores, total_results):
            item[dimension] = {"score": score, "full_judge": res}
        valid_scores = [score for score in eval_scores if score is not None]
        print(f"{dimension} score is: {np.mean(np.array(valid_scores))}")
        final_scores[dimension] = np.mean(np.array(valid_scores))
        total_score += np.mean(np.array(valid_scores))
        save_path = args.predict_path.split(".json")[0] + f"_fix_criteria_res.json"
        save_json(total_results, save_path)
    print(f"Evaluate: {args.predict_path}")
    print(f"Overall empathy score is: {total_score / 3 / 5}")
    print(final_scores)

if __name__ == "__main__":
    args = parse_args()
    eval(args)
